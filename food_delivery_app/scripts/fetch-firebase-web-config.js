const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const saPath = path.join(__dirname, '..', 'serviceAccountKey.json');
const sa = JSON.parse(fs.readFileSync(saPath, 'utf8'));
const PROJECT_ID = sa.project_id;

function base64url(buf) {
  return Buffer.from(buf).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}
function createJwt(sa) {
  const iat = Math.floor(Date.now() / 1000);
  const header = { alg: 'RS256', typ: 'JWT' };
  const claim = {
    iss: sa.client_email,
    scope: 'https://www.googleapis.com/auth/firebase',
    aud: sa.token_uri,
    iat,
    exp: iat + 3600
  };
  const toSign = base64url(JSON.stringify(header)) + '.' + base64url(JSON.stringify(claim));
  const sign = crypto.createSign('RSA-SHA256');
  sign.update(toSign);
  const signature = sign.sign(sa.private_key, 'base64');
  const sig = base64url(Buffer.from(signature, 'base64'));
  return toSign + '.' + sig;
}

async function getAccessToken(sa) {
  const jwt = createJwt(sa);
  const body = new URLSearchParams({
    grant_type: 'urn:ietf:params:oauth:grant-type:jwt-bearer',
    assertion: jwt
  }).toString();
  const res = await fetch(sa.token_uri, {
    method: 'POST',
    headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
    body
  });
  const json = await res.json();
  if (!res.ok) throw new Error('token error: ' + JSON.stringify(json));
  return json.access_token;
}

async function ensureWebAppAndConfig(projectId, token) {
  const listUrl = `https://firebase.googleapis.com/v1beta1/projects/${projectId}/webApps`;
  let res = await fetch(listUrl, { headers: { Authorization: `Bearer ${token}` } });
  let json = await res.json();
  if (!res.ok) throw new Error('webApps list error: ' + JSON.stringify(json));
  let apps = json.webApps || [];
  if (!apps.length) {
    const createRes = await fetch(listUrl, {
      method: 'POST',
      headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({ displayName: 'SmartSoko Web (auto-created)' })
    });
    const created = await createRes.json();
    if (!createRes.ok) throw new Error('webApp create error: ' + JSON.stringify(created));
    apps = [{ name: created.name }];
  }
  for (const app of apps) {
    const detailUrl = `https://firebase.googleapis.com/v1beta1/${app.name}/config`;
    const dres = await fetch(detailUrl, { headers: { Authorization: `Bearer ${token}` } });
    const djson = await dres.json();
    if (djson.apiKey) return djson;
  }
  throw new Error('Could not resolve web app config');
}

async function getProjectClientConfig(projectId, token) {
  const url = `https://firebase.googleapis.com/v1beta1/projects/${projectId}/config`;
  const res = await fetch(url, { headers: { Authorization: `Bearer ${token}` } });
  const json = await res.json();
  if (!res.ok) throw new Error('project config error: ' + JSON.stringify(json));
  return json;
}

(async () => {
  const token = await getAccessToken(sa);
  let apiKey = null;
  let config = null;
  try {
    const pc = await getProjectClientConfig(PROJECT_ID, token);
    if (pc.webApiKey) {
      apiKey = pc.webApiKey;
      config = {
        apiKey,
        authDomain: `${PROJECT_ID}.firebaseapp.com`,
        projectId: PROJECT_ID,
        storageBucket: `${PROJECT_ID}.appspot.com`,
        messagingSenderId: '',
        appId: ''
      };
    }
  } catch (e) { console.error('project config failed:', e.message); }
  if (!apiKey) {
    const wcfg = await ensureWebAppAndConfig(PROJECT_ID, token);
    apiKey = wcfg.apiKey;
    config = {
      apiKey,
      authDomain: wcfg.authDomain || `${PROJECT_ID}.firebaseapp.com`,
      projectId: PROJECT_ID,
      storageBucket: wcfg.storageBucket || `${PROJECT_ID}.appspot.com`,
      messagingSenderId: wcfg.messagingSenderId || '',
      appId: wcfg.appId || ''
    };
  }
  console.log('Resolved apiKey:', apiKey);
  console.log('Config:', JSON.stringify(config, null, 2));
  fs.writeFileSync(path.join(__dirname, 'config', 'firebase-config.js'),
`// AUTO-GENERATED by scripts/fetch-firebase-web-config.js
// Do not edit by hand.
export const firebaseConfig = ${JSON.stringify(config, null, 2)};
import { initializeApp } from "https://www.gstatic.com/firebasejs/9.22.0/firebase-app.js";
import { getAuth } from "https://www.gstatic.com/firebasejs/9.22.0/firebase-auth.js";
import { getFirestore } from "https://www.gstatic.com/firebasejs/9.22.0/firebase-firestore.js";
import { getAnalytics } from "https://www.gstatic.com/firebasejs/9.22.0/firebase-analytics.js";

const app = initializeApp(firebaseConfig);
export const auth = getAuth(app);
export const db = getFirestore(app);
export const analytics = typeof getAnalytics === 'function' ? getAnalytics(app) : null;
window.firebaseConfig = firebaseConfig;
window.auth = auth;
window.db = db;
`);
  console.log('Wrote config/firebase-config.js');
})().catch(e => { console.error(e.message); process.exit(1); });
